# ---------- plot block 3: orbit + dipole field (animated) ----------

# 1) Build the field grid
n = 6                                   # even n avoids sampling the origin (r = 0 -> division by zero)
axis = np.linspace(-2, 2, n)
X, Y, Z = np.meshgrid(axis, axis, axis)

Bx, By, Bz = magField(X, Y, Z)
B_mag = np.sqrt(Bx**2 + By**2 + Bz**2)

# 2) Colour each arrow by field strength (log scale, since B falls off as 1/r^3)
norm = colors.LogNorm(vmin=B_mag.min(), vmax=B_mag.max())
rgba = cm.viridis(norm(B_mag.ravel()))
# 3D quiver draws 3 line segments per arrow (shaft + 2 head strokes),
# so the colour list must be extended to match
rgba = np.concatenate((rgba, np.repeat(rgba, 2, axis=0)))

# 3) Set up the 3D figure
fig = plt.figure(figsize=(8, 7))
ax = fig.add_subplot(projection="3d")

ax.quiver(X, Y, Z, Bx, By, Bz, length=0.5, normalize=True, colors=rgba)
ax.scatter(sun.x, sun.y, sun.z, color="orange", s=150, label="Star")

ax.set_xlim(-3, 3); ax.set_ylim(-3, 3); ax.set_zlim(-3, 3)
ax.set_box_aspect((1, 1, 1))            # equal scaling so the orbit looks circular
ax.set_xlabel("x"); ax.set_ylabel("y"); ax.set_zlabel("z")
ax.set_title("Planet orbiting a star with a dipole magnetic field")

sm = cm.ScalarMappable(norm=norm, cmap="viridis")
fig.colorbar(sm, ax=ax, shrink=0.6, label="|B| (log scale)")

# 4) Animated artists: planet (dot) and trail (line), starting empty
planet, = ax.plot([], [], [], "bo", markersize=8, label="Planet")
trail,  = ax.plot([], [], [], "b-", alpha=0.5)
ax.legend()

# 5) Update function: called once per frame
def update(frame):
    px, py = positions[frame]
    planet.set_data([px], [py])
    planet.set_3d_properties([0])                      # orbit lies in the z = 0 plane

    trail.set_data(positions[:frame+1, 0], positions[:frame+1, 1])
    trail.set_3d_properties(np.zeros(frame + 1))
    return planet, trail

anim = FuncAnimation(fig, update, frames=len(positions), interval=30, blit=False)
