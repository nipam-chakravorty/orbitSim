class Star:
    def __init__(self, mass, x, y, z):
        self.mass = mass
        # position of the star
        self.x = x
        self.y = y
        self.z = z
    def GM (self):
        _GM = 4 * np.pi * np.pi / self.mass
        return _GM

def magField(x, y, z):
    mu_0 = 1
    dipole_moment = 1

    C = (mu_0 * dipole_moment) / (4 * np.pi)

    r = np.sqrt(x*x + y*y + z*z)
    r5 = r ** 5

    B_x = C * 3 * x * z / r5
    B_y = C * 3 * y * z / r5
    B_z = C * (2*z*z - x*x - y*y) / r5

    return B_x, B_y, B_z

sun = Star(1, 0, 0, 0)

#initial position of the planet
x = 1
