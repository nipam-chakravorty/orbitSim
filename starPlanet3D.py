# This model is to produce an 3D arrangement of the sunEarth model
# To model the magnetic field of the star a current carrying loop
# the star in this case is to be a static object without precession or field flip
# the magentic field is to be modelled as uniform without any fluctuation

import numpy as np
import matplotlib.pyplot as plt
from matplotlib import cm, colors

class Star:
    def __init__(self, mass, x, y, z):
        self.mass = mass
        # position of the star
        self.x = x
        self.y = y
        self.z = z

def magField(x, y, z):
    mu_0 = 1
    dipole_moment = 1

    C = (mu_0 * dipole_moment) / (4 * np.pi)

    r = np.sqrt(x*x + y*y + z*z)
    r5 = r ** 5

    B_x = C * 3 * x * z / r5
    B_y = C * 3 * y * z / r5
    B_z = C * (2*z*z - x*x - y*y) / r5

    return B_x, B_y, B_z

sun = Star(1, 0, 0, 0)

# following portion is generated by ai
n = 6
axis = np.linspace(-2, 2, n)
X, Y, Z = np.meshgrid(axis, axis, axis)

Bx, By, Bz = magField(X, Y, Z)   # pass the star in
B_mag = np.sqrt(Bx**2 + By**2 + Bz**2)

norm = colors.LogNorm(vmin=B_mag.min(), vmax=B_mag.max())
rgba = cm.viridis(norm(B_mag.ravel()))
rgba = np.concatenate((rgba, np.repeat(rgba, 2, axis=0)))

fig = plt.figure(figsize=(8, 7))
ax = fig.add_subplot(projection="3d")
ax.quiver(X, Y, Z, Bx, By, Bz, length=0.5, normalize=True, colors=rgba)
ax.scatter(sun.x, sun.y, sun.z, color="orange", s=150, label="Star")

ax.set_xlabel("x"); ax.set_ylabel("y"); ax.set_zlabel("z")
ax.set_title("Dipole magnetic field")
ax.legend()

sm = cm.ScalarMappable(norm=norm, cmap="viridis")
fig.colorbar(sm, ax=ax, shrink=0.6, label="|B| (log scale)")
plt.show()